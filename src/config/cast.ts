/**
 * Retrieve a cast template by its unique ID.
 */
export function getCastById(id: string): CastTemplateRule | undefined {
  return CAST_REGISTRY.find((cast) => cast.id === id);
}

/**
 * Retrieve a cast template by its URL slug.
 */
export function getCastBySlug(slug: string): CastTemplateRule | undefined {
  return CAST_REGISTRY.find((cast) => cast.slug === slug);
}

/**
 * Filter cast templates by Star Tier (4 or 5).
 */
export function getCastByStarTier(tier: StarTier): CastTemplateRule[] {
  return CAST_REGISTRY.filter((cast) => cast.starTier === tier);
}

/**
 * Get all published, publicly discoverable cast templates.
 */
export function getAllPublicCasts(): CastTemplateRule[] {
  return CAST_REGISTRY.filter(
    (cast) => cast.status === "published" && cast.discoveryVisibility === "public"
  );
}

/**
 * Search cast templates by name, title, archetype, or trigger keywords.
 */
export function searchCasts(query: string): CastTemplateRule[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return getAllPublicCasts();

  return CAST_REGISTRY.filter((cast) => {
    if (cast.status !== "published") return false;
    return (
      cast.name.toLowerCase().includes(normalized) ||
      cast.knownName.toLowerCase().includes(normalized) ||
      cast.title.toLowerCase().includes(normalized) ||
      cast.archetype.toLowerCase().includes(normalized) ||
      cast.compatibilityTags.some((tag) => tag.toLowerCase().includes(normalized)) ||
      cast.triggerKeywords.some((kw) => kw.toLowerCase().includes(normalized))
    );
  });
}
